export function getAllBrands(): string[] {
  return [...new Set(indianCars.map((car) => car.brand))].sort();
}

export function filterCars(filters: {
  brand?: string;
  segment?: Segment;
  fuelType?: FuelType;
  priceMin?: number;
  priceMax?: number;
  searchQuery?: string;
}): IndianCar[] {
  return indianCars.filter((car) => {
    if (filters.brand && car.brand !== filters.brand) return false;
    if (filters.segment && car.segment !== filters.segment) return false;
    if (filters.fuelType && !car.fuelTypes.includes(filters.fuelType)) return false;
    if (filters.priceMin && car.priceMax < filters.priceMin) return false;
    if (filters.priceMax && car.priceMin > filters.priceMax) return false;
    if (filters.searchQuery) {
      const q = filters.searchQuery.toLowerCase();
      return (
        car.brand.toLowerCase().includes(q) ||
        car.model.toLowerCase().includes(q) ||
        car.segment.toLowerCase().includes(q)
      );
    }
    return true;
  });
}

export function getCarBySlug(slug: string): IndianCar | undefined {
  return indianCars.find((car) => car.slug === slug);
}

export function getPopularCars(): IndianCar[] {
  return indianCars.filter((car) => car.popular);
}

export function getCarsForComparison(ids: string[]): IndianCar[] {
  return indianCars.filter((car) => ids.includes(car.id));
}

export function formatPrice(price: number): string {
  return `₹${price.toFixed(2)} Lakh`;
}

export function formatPriceRange(min: number, max: number): string {
  return `₹${min.toFixed(2)} - ${max.toFixed(2)} Lakh`;
}

export function getTotalCarCount(): number {
  return indianCars.length;
}
